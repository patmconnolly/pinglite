//Convert a string of numbers to a long long int.
long long record::stringToLongLong(const std::string& str)
{
	long long result = 0;
	std::stringstream ss(str);

	if (ss >> result) {
		// Check if there are any remaining characters after the number
		char remaining;
		if (ss >> remaining) {
			// String contains non-numeric characters after the number
			throw std::invalid_argument("String contains non-numeric characters.");
		}
		return result;
	}
	else {
		// String is not a valid number
		throw std::invalid_argument("Invalid number string.");
	}
}

//Int snooze in minutes.
bool record::isAlertSnoozeExpired(int SNOOZE)
{
	return this->isSnoozeExpired(SNOOZE * 60, this->LASTALERT);
}

//Int snooze in days.
bool record::isWarnSnoozeExpired(int SNOOZE)
{
	return this->isSnoozeExpired(SNOOZE * 24 * 60 * 60, this->LASTSSLWARNING);
}

//Int snooze in seconds, long long last is time to compare to of last alert.
bool record::isSnoozeExpired(int SNOOZE, long long LAST)
{
	long long snoozeLong = static_cast<long long>(SNOOZE);
	long long differenceSeconds = this->NOW - LAST;
	return differenceSeconds > snoozeLong;
}

